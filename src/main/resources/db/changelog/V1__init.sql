CREATE TABLE IF NOT EXISTS element_info (
                                            id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                            element_id BIGINT NOT NULL,
                                            state varchar(20) NOT NULL,
    count int8 NULL,
    price NUMERIC(10, 2) NULL,
    price_kuboka NUMERIC(10, 2) NULL,
    created TIMESTAMP NULL DEFAULT NOW(),
    updated TIMESTAMP NULL,
    count_updated TIMESTAMP NULL,
    price_updated TIMESTAMP NULL,
    price_kuboka_updated TIMESTAMP NULL,
    CONSTRAINT element_info_pk PRIMARY KEY (id),
    CONSTRAINT element_info_element_fk FOREIGN KEY (element_id) REFERENCES elements(id),
    CONSTRAINT element_id_state_uc UNIQUE (element_id, state)
    );
CREATE INDEX IF NOT EXISTS element_info_element_id_idx ON element_info USING btree (element_id);