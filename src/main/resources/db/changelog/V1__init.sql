    CONSTRAINT inventory_id_minifig_id_uc UNIQUE (inventory_id, minifig_id)
    );
CREATE INDEX IF NOT EXISTS inventory_minifigs_inventory_id_idx ON inventory_minifigs USING btree (inventory_id);
CREATE INDEX IF NOT EXISTS inventory_minifigs_minifig_id_idx ON inventory_minifigs USING btree (minifig_id);

----
CREATE TABLE IF NOT EXISTS inventory_sets (
                                              id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                              inventory_id BIGINT NULL,
                                              set_id BIGINT NULL,
                                              quantity int4 NULL,
                                              CONSTRAINT inventory_sets_pk PRIMARY KEY (id),
    CONSTRAINT inv_sets_inv_fk FOREIGN KEY (inventory_id) REFERENCES inventories(id),
